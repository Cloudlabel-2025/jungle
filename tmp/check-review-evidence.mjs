import { build } from 'esbuild';
import { createRequire } from 'node:module';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import assert from 'node:assert/strict';
await build({ entryPoints: ['components/DayOneReviewEvidence.js'], bundle: true, platform: 'node', packages: 'external', loader: { '.js': 'jsx' }, jsx: 'automatic', format: 'cjs', outfile: 'tmp/review-evidence.cjs' });
const Evidence = createRequire(import.meta.url)('./review-evidence.cjs').default;
const record = { config: { genres: [] }, researchAssignment: { genreName: 'Fitness', question: { title: 'The sport nobody knows', prompt: 'Compare three local sports.' } }, acknowledgedAt: 'accepted', startedAt: 'started', submissions: [{ url: 'https://example.org/chat', at: 'submitted' }], verification: { status: 'PENDING' } };
const render = (r, canVerify = true) => renderToStaticMarkup(React.createElement(Evidence, { record: r, canVerify, formatDate: x => x }));
let html = render(record);
for (const text of ['Fitness', 'The sport nobody knows', 'Compare three local sports.', 'https://example.org/chat', 'Awaiting Centre Command', '1 saved submission']) assert.ok(html.includes(text), text);
assert.ok(!html.includes('AI chat verified.'));
html = render(record, false);
assert.ok(html.includes('The sport nobody knows'));
assert.ok(!html.includes('href='));
assert.ok(render({ ...record, submissions: [], draft: { url: 'draft' } }).includes('has not been submitted'));
assert.ok(render({ ...record, submissions: [] }).includes('No AI chat has been submitted yet'));
assert.ok(render({ ...record, verification: { status: 'VERIFIED' } }).includes('AI chat verified.'));
assert.ok(render({ ...record, verification: { status: 'INACCESSIBLE' } }).includes('access correction'));
console.log('PASS: Saved question, prompt, submission and pending/verified/correction states render; draft is not treated as submitted; MC verification restriction preserved.');
